-- Run only against a disposable PostgreSQL database with psql:
-- psql -X -v ON_ERROR_STOP=1 -d <disposable_database> \
--   -f database/validation/validate_V9__support_brute_force_security_events.sql
--
-- The validation creates an isolated Phase 8-style schema, applies the Phase 9
-- upgrade twice, verifies compatibility and preservation, and rolls back.
\set ON_ERROR_STOP on

BEGIN;

DO $validation_setup$
BEGIN
    IF to_regnamespace('phase_9_validation') IS NOT NULL THEN
        RAISE EXCEPTION 'Schema phase_9_validation already exists; use a clean disposable database';
    END IF;
END
$validation_setup$;

CREATE SCHEMA phase_9_validation;
SET LOCAL search_path TO phase_9_validation, pg_catalog;

CREATE TABLE security_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type character varying(64) NOT NULL,
    source_request_log_id bigint NOT NULL,
    CONSTRAINT ck_security_event_event_type_values
        CHECK (event_type IN ('EXCESSIVE_REQUESTS', 'XSS_ATTEMPT', 'SQL_INJECTION_ATTEMPT'))
);

INSERT INTO security_event (event_type, source_request_log_id)
VALUES
    ('EXCESSIVE_REQUESTS', 41),
    ('XSS_ATTEMPT', 42),
    ('SQL_INJECTION_ATTEMPT', 43);

\ir ../migrations/V9__support_brute_force_security_events.sql
\ir ../migrations/V9__support_brute_force_security_events.sql

INSERT INTO security_event (event_type, source_request_log_id)
VALUES ('BRUTE_FORCE_ATTEMPT', NULL);

DO $validation_assertions$
DECLARE
    preserved_rows integer;
    preserved_sources integer;
    compatible_constraints integer;
    source_id_is_not_null boolean;
    unsupported_value_rejected boolean := false;
BEGIN
    SELECT count(*) INTO preserved_rows FROM security_event;
    IF preserved_rows <> 4 THEN
        RAISE EXCEPTION 'Expected four preserved/inserted rows, found %', preserved_rows;
    END IF;

    SELECT count(*) INTO preserved_sources
    FROM security_event
    WHERE (event_type = 'EXCESSIVE_REQUESTS' AND source_request_log_id = 41)
       OR (event_type = 'XSS_ATTEMPT' AND source_request_log_id = 42)
       OR (event_type = 'SQL_INJECTION_ATTEMPT' AND source_request_log_id = 43);
    IF preserved_sources <> 3 THEN
        RAISE EXCEPTION 'Existing source request identifiers were not preserved';
    END IF;

    SELECT attribute.attnotnull INTO source_id_is_not_null
    FROM pg_attribute attribute
    WHERE attribute.attrelid = 'security_event'::regclass
      AND attribute.attname = 'source_request_log_id'
      AND NOT attribute.attisdropped;
    IF source_id_is_not_null THEN
        RAISE EXCEPTION 'Expected source_request_log_id to allow null values';
    END IF;

    SELECT count(*) INTO compatible_constraints
    FROM pg_constraint constraint_entry
    WHERE constraint_entry.conrelid = 'security_event'::regclass
      AND constraint_entry.contype = 'c'
      AND position('EXCESSIVE_REQUESTS' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('XSS_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('SQL_INJECTION_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('BRUTE_FORCE_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0;
    IF compatible_constraints <> 1 THEN
        RAISE EXCEPTION 'Expected one compatible event_type constraint, found %', compatible_constraints;
    END IF;

    BEGIN
        INSERT INTO security_event (event_type, source_request_log_id)
        VALUES ('UNSUPPORTED_EVENT', NULL);
    EXCEPTION
        WHEN check_violation THEN
            unsupported_value_rejected := true;
    END;
    IF NOT unsupported_value_rejected THEN
        RAISE EXCEPTION 'Unsupported event type was not rejected';
    END IF;
END
$validation_assertions$;

ROLLBACK;
