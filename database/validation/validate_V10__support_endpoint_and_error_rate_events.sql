DO $validation_assertions$
DECLARE
    preserved_rows integer;
    preserved_sources integer;
    compatible_constraints integer;
    compatible_columns integer;
    unsuccessful_requests bigint;
    distinct_paths bigint;
    total_requests bigint;
    client_errors bigint;
    server_errors bigint;
    unsupported_value_rejected boolean := false;
BEGIN
    SELECT count(*) INTO preserved_rows FROM security_event;
    IF preserved_rows <> 6 THEN
        RAISE EXCEPTION 'Expected six preserved/inserted rows, found %', preserved_rows;
    END IF;

    SELECT count(*) INTO preserved_sources
    FROM security_event
    WHERE (event_type = 'EXCESSIVE_REQUESTS' AND source_request_log_id = 41)
       OR (event_type = 'XSS_ATTEMPT' AND source_request_log_id = 42)
       OR (event_type = 'SQL_INJECTION_ATTEMPT' AND source_request_log_id = 43)
       OR (event_type = 'BRUTE_FORCE_ATTEMPT' AND source_request_log_id IS NULL);
    IF preserved_sources <> 4 THEN
        RAISE EXCEPTION 'Existing events or source request identifiers were not preserved';
    END IF;

    SELECT count(*) INTO compatible_columns
    FROM pg_attribute attribute
    WHERE attribute.attrelid = 'security_event'::regclass
      AND NOT attribute.attisdropped
      AND NOT attribute.attnotnull
      AND (
          (attribute.attname = 'observed_distinct_path_count'
              AND format_type(attribute.atttypid, attribute.atttypmod) = 'bigint')
          OR (attribute.attname = 'configured_distinct_path_threshold'
              AND format_type(attribute.atttypid, attribute.atttypmod) = 'integer')
          OR (attribute.attname = 'observed_client_error_count'
              AND format_type(attribute.atttypid, attribute.atttypmod) = 'bigint')
          OR (attribute.attname = 'configured_client_error_rate_percent'
              AND format_type(attribute.atttypid, attribute.atttypmod) = 'integer')
      );
    IF compatible_columns <> 4 THEN
        RAISE EXCEPTION 'Expected four compatible nullable evidence columns, found %', compatible_columns;
    END IF;

    SELECT count(*) INTO compatible_constraints
    FROM pg_constraint constraint_entry
    WHERE constraint_entry.conrelid = 'security_event'::regclass
      AND constraint_entry.contype = 'c'
      AND position('EXCESSIVE_REQUESTS' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('XSS_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('SQL_INJECTION_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('BRUTE_FORCE_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('ENDPOINT_SCANNING' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('ABNORMAL_ERROR_RATE' IN pg_get_constraintdef(constraint_entry.oid)) > 0;
    IF compatible_constraints <> 1 THEN
        RAISE EXCEPTION 'Expected one compatible event_type constraint, found %', compatible_constraints;
    END IF;

    SELECT count(*), count(DISTINCT request_path)
    INTO unsuccessful_requests, distinct_paths
    FROM api_request_log
    WHERE client_ip = '192.0.2.10'
      AND requested_at >= '2026-11-27T10:00:00Z'
      AND requested_at <= '2026-11-27T10:01:00Z'
      AND response_status = 404;
    IF unsuccessful_requests <> 8 OR distinct_paths <> 5 THEN
        RAISE EXCEPTION
            'Unexpected endpoint aggregate: requests %, distinct paths %',
            unsuccessful_requests,
            distinct_paths;
    END IF;

    SELECT count(*),
           count(*) FILTER (
               WHERE response_status BETWEEN 400 AND 499
                 AND response_status NOT IN (401, 403, 429)),
           count(*) FILTER (WHERE response_status BETWEEN 500 AND 599)
    INTO total_requests, client_errors, server_errors
    FROM api_request_log
    WHERE client_ip = '192.0.2.10'
      AND requested_at >= '2026-11-27T10:00:00Z'
      AND requested_at <= '2026-11-27T10:01:00Z';
    IF total_requests <> 13 OR client_errors <> 8 OR server_errors <> 1 THEN
        RAISE EXCEPTION
            'Unexpected error-rate aggregate: total %, client errors %, server errors %',
            total_requests,
            client_errors,
            server_errors;
    END IF;

    BEGIN
        INSERT INTO security_event (
            event_type,
            source_request_log_id,
            observed_request_count,
            configured_threshold,
            window_seconds
        )
        VALUES ('UNSUPPORTED_EVENT', NULL, 1, 1, 1);
    EXCEPTION
        WHEN check_violation THEN
            unsupported_value_rejected := true;
    END;
    IF NOT unsupported_value_rejected THEN
        RAISE EXCEPTION 'Unsupported event type was not rejected';
    END IF;
END
$validation_assertions$;

ROLLBACK;
