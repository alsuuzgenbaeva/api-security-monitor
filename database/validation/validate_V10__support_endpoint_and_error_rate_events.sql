CREATE TABLE security_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type character varying(64) NOT NULL,
    source_request_log_id bigint,
    observed_request_count bigint NOT NULL,
    configured_threshold integer NOT NULL,
    window_seconds bigint NOT NULL,
    CONSTRAINT ck_security_event_event_type_values
        CHECK (event_type IN (
            'EXCESSIVE_REQUESTS',
            'XSS_ATTEMPT',
            'SQL_INJECTION_ATTEMPT',
            'BRUTE_FORCE_ATTEMPT'))
);

CREATE TABLE api_request_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_at timestamp with time zone NOT NULL,
    client_ip character varying(45) NOT NULL,
    request_path character varying(2048) NOT NULL,
    response_status integer NOT NULL
);

