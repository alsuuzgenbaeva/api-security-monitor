-- Run only against a disposable PostgreSQL database with psql:
-- psql -X -v ON_ERROR_STOP=1 -d <disposable_database> \
--   -f database/validation/validate_V8_1__expand_security_event_type_check.sql
--
-- The validation creates an isolated schema, applies the upgrade twice, checks
-- old and new values, and rolls everything back.
\set ON_ERROR_STOP on

BEGIN;

DO $validation_setup$
BEGIN
    IF to_regnamespace('phase_8_1_validation') IS NOT NULL THEN
        RAISE EXCEPTION 'Schema phase_8_1_validation already exists; use a clean disposable database';
    END IF;
END
$validation_setup$;

CREATE SCHEMA phase_8_1_validation;
SET LOCAL search_path TO phase_8_1_validation, pg_catalog;

CREATE TABLE security_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type character varying(64) NOT NULL,
    CONSTRAINT old_security_event_type_check
        CHECK (event_type IN ('EXCESSIVE_REQUESTS'))
);

INSERT INTO security_event (event_type) VALUES ('EXCESSIVE_REQUESTS');

\ir ../migrations/V8_1__expand_security_event_type_check.sql
\ir ../migrations/V8_1__expand_security_event_type_check.sql

INSERT INTO security_event (event_type)
VALUES ('XSS_ATTEMPT'), ('SQL_INJECTION_ATTEMPT');

DO $validation_assertions$
DECLARE
    preserved_rows integer;
    compatible_constraints integer;
BEGIN
    SELECT count(*) INTO preserved_rows FROM security_event;
    IF preserved_rows <> 3 THEN
        RAISE EXCEPTION 'Expected three preserved/inserted rows, found %', preserved_rows;
    END IF;

    SELECT count(*) INTO compatible_constraints
    FROM pg_constraint constraint_entry
    WHERE constraint_entry.conrelid = 'security_event'::regclass
      AND constraint_entry.contype = 'c'
      AND position('EXCESSIVE_REQUESTS' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('XSS_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0
      AND position('SQL_INJECTION_ATTEMPT' IN pg_get_constraintdef(constraint_entry.oid)) > 0;

    IF compatible_constraints <> 1 THEN
        RAISE EXCEPTION 'Expected one compatible event_type constraint, found %', compatible_constraints;
    END IF;
END
$validation_assertions$;

ROLLBACK;
